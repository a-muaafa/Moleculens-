def _build_compound(row: tuple) -> dict:
    (key, subclass, formula, name_en, name_ar, smiles, cid, syn_ar, syn_en, abbrevs, iupac, desc) = row
    mass = calculate_molar_mass(formula)
    if mass is None:
        try:
            from rdkit import Chem
            from rdkit.Chem import Descriptors
            m = Chem.MolFromSmiles(smiles)
            mass = round(Descriptors.MolWt(m), 3) if m is not None else None
        except Exception:
            mass = None
    entity_type = _ENTITY_BY_SUBCLASS.get(subclass, ENTITY_CHEMICAL_COMPOUND)
    phase_code = "aq" if subclass == "ion" else get_standard_phase_code(formula)
    phys_state_ar = _PHYSICAL_STATE_BY_PHASE.get(phase_code, "صلب بلوري في الظروف القياسية")

    entry = {
        "key": key,
        "entity_type": entity_type,
        "subclass": subclass,
        "name_ar": name_ar,
        "name_en": name_en,
        "iupac_name": iupac,
        "symbol_or_formula": formula,
        "canonical_smiles": smiles,
        "molar_mass": mass,
        "pubchem_cid": cid,
        "abbreviations": list(abbrevs),
        "brand_names": [],
        "synonyms_ar": [name_ar, *syn_ar],
        "synonyms_en": [name_en, *syn_en],
        "structure_details": {
            "molecular_geometry": "تفاصيل البنية الجزيئية والروابط محللة حتمياً من البنية الكيميائية المرجعية عبر محرك RDKit.",
            "chemical_bonds": f"التمثيل البنيوي الجزيئي المعتمد (Canonical SMILES): {smiles}",
        },
        "physical_properties": {
            "physical_state": phys_state_ar,
        },
        "chemical_properties": {"reactivity": _PHASE_HINT_AR.get(subclass, "")},
        "applications": {
            "daily": desc,
            "industrial": "يدخل في الصناعات الكيميائية والدوائية والتحليلية الموثقة في سجل PubChem.",
            "scientific": "مرجع معتمد لدراسة التراكيب الجزيئية ثنائية وثلاثية الأبعاد والحسابات المولية في المختبر.",
        },
        "education_notes": {
            "student_level_ar": f"{name_ar} ({formula}): {desc}",
            "advanced_level_ar": f"{name_ar} ({formula}) كتلته المولية (Molar Mass) تبلغ {mass} g/mol وتصنيفه الكيميائي: {_PHASE_HINT_AR.get(subclass, '')}",
        },
        "sources": ["PubChem", "RDKit Chemistry Engine", "Curated Scientific Catalog"],
    }
    if key in _DRUG_PHARM:
        cls, ind, tgt, mech, chembl_id = _DRUG_PHARM[key]
        entry["chembl_id"] = chembl_id
        entry["pharmacology_details"] = {
            "therapeutic_class_ar": cls,
            "indication_ar": ind,
            "target_protein_ar": tgt,
            "mechanism_of_action_ar": mech,
            "documented_bioactivity_ar": f"موثق في قاعدة البيانات الدوائية ChEMBL (المعرف المرجعي: {chembl_id}).",
            "approval_status_ar": "مادة دوائية معتمدة سريرياً ودستورياً (FDA / EMA / USP Approved).",
        }
        entry["sources"] = ["ChEMBL", "PubChem", "RDKit Chemistry Engine", "Curated Scientific Catalog"]
        entry["brand_names"] = [b for b in syn_en if b.lower() != name_en.lower() and not b[0].isdigit()][:2]
    return entry


def _period_for(z: int) -> int:
    for limit, period in ((2, 1), (10, 2), (18, 3), (36, 4), (54, 5), (86, 6)):
        if z <= limit:
            return period
    return 7


