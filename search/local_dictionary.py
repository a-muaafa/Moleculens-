def normalize_arabic_text(text: str) -> str:
    if not text:
        return ""
    s = text.strip().lower()
    s = re.sub(r"[\u064B-\u065F\u0670]", "", s)
    s = re.sub(r"[أإآٱ]", "ا", s)
    s = s.replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    s = re.sub(r"\s+", " ", s)
    return s


def get_all_local_compounds() -> list:
    return [dict(item) for item in LOCAL_COMPOUND_DICTIONARY]

